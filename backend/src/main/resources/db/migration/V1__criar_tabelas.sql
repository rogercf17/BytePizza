-- Catálogo
CREATE TABLE categoria (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome   VARCHAR(60) NOT NULL UNIQUE,
    ordem  INT         NOT NULL DEFAULT 0,
    ativa  BOOLEAN     NOT NULL DEFAULT TRUE
);

CREATE TABLE sabor (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id  BIGINT         NOT NULL REFERENCES categoria (id),
    nome          VARCHAR(80)    NOT NULL UNIQUE,
    descricao     VARCHAR(255),
    preco         NUMERIC(10, 2) NOT NULL CHECK (preco > 0),
    vegetariano   BOOLEAN        NOT NULL DEFAULT FALSE,
    imagem_url    VARCHAR(255),
    ativo         BOOLEAN        NOT NULL DEFAULT TRUE
);

CREATE INDEX idx_sabor_categoria ON sabor (categoria_id);

-- Operação da loja
CREATE TABLE configuracao_loja (
    id                     BIGINT PRIMARY KEY CHECK (id = 1),
    pedido_minimo          NUMERIC(10, 2) NOT NULL DEFAULT 0 CHECK (pedido_minimo >= 0),
    loja_pausada           BOOLEAN        NOT NULL DEFAULT FALSE,
    validade_pix_minutos   INT            NOT NULL DEFAULT 15 CHECK (validade_pix_minutos > 0),
    mensagem_aviso         VARCHAR(255),
    latitude_loja          NUMERIC(9, 6)  NOT NULL,
    longitude_loja         NUMERIC(9, 6)  NOT NULL,
    taxa_base              NUMERIC(10, 2) NOT NULL DEFAULT 7.00 CHECK (taxa_base >= 0),
    raio_taxa_base_km      NUMERIC(4, 1)  NOT NULL DEFAULT 5 CHECK (raio_taxa_base_km >= 0),
    taxa_por_km_excedente  NUMERIC(10, 2) NOT NULL DEFAULT 2.00 CHECK (taxa_por_km_excedente >= 0),
    prazo_min_minutos      INT            NOT NULL DEFAULT 30,
    prazo_max_minutos      INT            NOT NULL DEFAULT 45
);

CREATE TABLE horario_funcionamento (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dia_semana  SMALLINT NOT NULL CHECK (dia_semana BETWEEN 0 AND 6),
    abre        TIME     NOT NULL,
    fecha       TIME     NOT NULL
);

-- Cliente (convidado, sem senha)
CREATE TABLE cliente (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                    VARCHAR(100) NOT NULL,
    telefone                VARCHAR(20)  NOT NULL,
    consentimento_whatsapp  BOOLEAN      NOT NULL DEFAULT FALSE,
    criado_em               TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_cliente_telefone ON cliente (telefone);

-- Pedido
CREATE TABLE pedido (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_publico      UUID           NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    chave_idempotencia  VARCHAR(60)    UNIQUE,
    cliente_id          BIGINT         NOT NULL REFERENCES cliente (id),
    status              VARCHAR(30)    NOT NULL
        CHECK (status IN ('AGUARDANDO_PAGAMENTO', 'PAGO', 'PREPARANDO',
                          'SAIU_PARA_ENTREGA', 'ENTREGUE', 'CANCELADO')),
    subtotal            NUMERIC(10, 2) NOT NULL CHECK (subtotal >= 0),
    taxa_entrega        NUMERIC(10, 2) NOT NULL CHECK (taxa_entrega >= 0),
    total               NUMERIC(10, 2) NOT NULL CHECK (total >= 0),
    distancia_km        NUMERIC(5, 2),
    prazo_estimado_min  INT,
    prazo_estimado_max  INT,
    cep                 VARCHAR(8)     NOT NULL,
    logradouro          VARCHAR(120)   NOT NULL,
    numero              VARCHAR(10)    NOT NULL,
    complemento         VARCHAR(60),
    bairro              VARCHAR(80)    NOT NULL,
    cidade              VARCHAR(80)    NOT NULL,
    uf                  CHAR(2)        NOT NULL,
    latitude_entrega    NUMERIC(9, 6),
    longitude_entrega   NUMERIC(9, 6),
    observacao          VARCHAR(255),
    criado_em           TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    atualizado_em       TIMESTAMPTZ    NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_pedido_cliente ON pedido (cliente_id);
CREATE INDEX idx_pedido_status ON pedido (status);
CREATE INDEX idx_pedido_criado_em ON pedido (criado_em);

CREATE TABLE item_pedido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT         NOT NULL REFERENCES pedido (id) ON DELETE CASCADE,
    tipo            VARCHAR(20)    NOT NULL CHECK (tipo IN ('INTEIRA', 'MEIO_A_MEIO')),
    quantidade      INT            NOT NULL CHECK (quantidade BETWEEN 1 AND 20),
    preco_unitario  NUMERIC(10, 2) NOT NULL CHECK (preco_unitario >= 0),
    observacao      VARCHAR(255)
);

CREATE INDEX idx_item_pedido_pedido ON item_pedido (pedido_id);

CREATE TABLE item_pedido_sabor (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_pedido_id  BIGINT         NOT NULL REFERENCES item_pedido (id) ON DELETE CASCADE,
    sabor_id        BIGINT         NOT NULL REFERENCES sabor (id),
    posicao         SMALLINT       NOT NULL CHECK (posicao IN (1, 2)),
    nome_sabor      VARCHAR(80)    NOT NULL,
    preco_sabor     NUMERIC(10, 2) NOT NULL CHECK (preco_sabor >= 0),
    UNIQUE (item_pedido_id, posicao)
);

CREATE TABLE historico_status_pedido (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id        BIGINT      NOT NULL REFERENCES pedido (id) ON DELETE CASCADE,
    status_anterior  VARCHAR(30),
    status_novo      VARCHAR(30) NOT NULL,
    origem           VARCHAR(30) NOT NULL
        CHECK (origem IN ('SISTEMA', 'WEBHOOK_PAGAMENTO', 'COZINHA', 'JOB_EXPIRACAO')),
    criado_em        TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_historico_pedido ON historico_status_pedido (pedido_id);

-- Pagamento
CREATE TABLE pagamento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id       BIGINT         NOT NULL REFERENCES pedido (id),
    provedor        VARCHAR(30)    NOT NULL,
    id_externo      VARCHAR(60)    UNIQUE,
    metodo          VARCHAR(20)    NOT NULL CHECK (metodo IN ('PIX', 'CARTAO')),
    status          VARCHAR(30)    NOT NULL
        CHECK (status IN ('PENDENTE', 'APROVADO', 'RECUSADO', 'EXPIRADO',
                          'CANCELADO', 'ESTORNADO')),
    valor           NUMERIC(10, 2) NOT NULL CHECK (valor > 0),
    pix_qr_code     TEXT,
    pix_copia_cola  TEXT,
    expira_em       TIMESTAMPTZ,
    criado_em       TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    atualizado_em   TIMESTAMPTZ    NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_pagamento_pedido ON pagamento (pedido_id);
CREATE INDEX idx_pagamento_status_expira ON pagamento (status, expira_em);

CREATE TABLE evento_webhook (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provedor           VARCHAR(30) NOT NULL,
    id_evento_externo  VARCHAR(80) NOT NULL,
    payload            JSONB       NOT NULL,
    assinatura_valida  BOOLEAN     NOT NULL,
    processado         BOOLEAN     NOT NULL DEFAULT FALSE,
    recebido_em        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (provedor, id_evento_externo)
);

-- Integração e mensagens (outbox)
CREATE TABLE outbox_mensagem (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id             BIGINT       NOT NULL REFERENCES pedido (id),
    tipo                  VARCHAR(40)  NOT NULL
        CHECK (tipo IN ('PEDIDO_CONFIRMADO', 'SAIU_PARA_ENTREGA', 'ENVIO_SISTEMA_INTERNO')),
    destino               VARCHAR(120) NOT NULL,
    payload               JSONB        NOT NULL,
    status                VARCHAR(20)  NOT NULL DEFAULT 'PENDENTE'
        CHECK (status IN ('PENDENTE', 'ENVIADA', 'FALHA')),
    tentativas            INT          NOT NULL DEFAULT 0,
    proxima_tentativa_em  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    ultimo_erro           TEXT,
    criado_em             TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_outbox_pendentes ON outbox_mensagem (status, proxima_tentativa_em);
CREATE INDEX idx_outbox_pedido ON outbox_mensagem (pedido_id);